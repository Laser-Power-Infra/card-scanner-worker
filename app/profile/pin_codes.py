"""Offline India PIN lookup (state, district, city, centroid).

The table is generated by ``scripts/build_pin_prefixes.py`` from GeoNames and
committed as ``data/india_pins.json``. It is intentionally small and local:
the address pass must work without another network dependency, and an invalid
PIN such as 996544 must be rejected before it reaches the geocoder.
"""
import json
import logging
import re
import threading
from pathlib import Path

log = logging.getLogger("card-desk.pin-codes")

_DATA_PATH = Path(__file__).resolve().parents[2] / "data" / "india_pins.json"

_lock = threading.Lock()
_data = None
_missing_warned = False


def _load():
    global _data, _missing_warned
    if _data is not None:
        return _data
    with _lock:
        if _data is not None:
            return _data
        try:
            raw = json.loads(_DATA_PATH.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            if not _missing_warned:
                log.warning("PIN table unavailable at %s: %s", _DATA_PATH, exc)
                _missing_warned = True
            raw = {"states": [], "districts": [], "cities": [], "pins": {}}
        _data = raw
        return _data


def normalize_pin(value):
    """Return a 6-digit PIN from text such as ``700 160`` or ``700-160``."""
    digits = re.sub(r"\D", "", str(value or ""))
    if len(digits) != 6 or digits[0] == "0":
        return ""
    return digits


def lookup(pin):
    """Return a PIN record, or an invalid record when the PIN is unknown.

    The record shape is stable so callers do not need to branch:
        {"pin", "valid", "state", "district", "city", "lat", "lon"}
    """
    normalized = normalize_pin(pin)
    empty = {"pin": normalized, "valid": False, "state": "", "district": "",
             "city": "", "lat": None, "lon": None}
    if not normalized:
        return empty
    data = _load()
    row = (data.get("pins") or {}).get(normalized)
    if not row:
        return empty
    states = data.get("states") or []
    districts = data.get("districts") or []
    cities = data.get("cities") or []

    def _name(values, index):
        try:
            return values[int(index)] or ""
        except (IndexError, TypeError, ValueError):
            return ""

    return {
        "pin": normalized,
        "valid": True,
        "state": _name(states, row[0]),
        "district": _name(districts, row[1]),
        "city": _name(cities, row[2]),
        "lat": row[3] if len(row) > 3 else None,
        "lon": row[4] if len(row) > 4 else None,
    }


def is_valid(pin):
    return lookup(pin)["valid"]


def states():
    return list(_load().get("states") or [])


